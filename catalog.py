#!/usr/bin/env python3
"""Regenerate the kit's catalog: what exists, what's proposed, what's waiting in the inbox.

    python3 catalog.py            # rebuild every scene, render previews, write CATALOG.md + library.json
    python3 catalog.py --no-render  # only rewrite CATALOG.md + library.json from what's already rendered

Reads catalog.json (primitives and scenes), proposals.json, references/ and inbox/.
Writes catalog/<scene>.{ecproj,png,gif,mp4}, CATALOG.md (browse it on GitHub) and library.json
(add the kit folder in EffectCraft with library.addFolder to see it in the Motion Library panel).
EFFECTCRAFT_CLI picks the CLI (default: effectcraft-cli on PATH).
"""
import json
import os
import subprocess
import sys

KIT = os.path.dirname(os.path.abspath(__file__))
CLI = os.environ.get("EFFECTCRAFT_CLI", "effectcraft-cli")
TICKS = 254_016_000_000  # EffectCraft time units per second


def load(name, default):
    path = os.path.join(KIT, name)
    if not os.path.exists(path):
        return default
    with open(path) as f:
        return json.load(f)


def cli(*args):
    r = subprocess.run([CLI, *args], capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit(f"effectcraft-cli {' '.join(args[:2])} failed:\n{r.stderr or r.stdout}")
    return r.stdout


def render_scene(sid):
    out = os.path.join(KIT, "catalog")
    proj = os.path.join(out, f"{sid}.ecproj")
    cli("script", os.path.join(KIT, f"{sid}.jsx"), "--empty", "--save-as", proj)
    cli("render-frame", proj, "--comp", "Main", "--time", "1", "--max-side", "640", "--out", os.path.join(out, f"{sid}.png"))
    cli("render", proj, "--comp", "Main", "--out", os.path.join(out, f"{sid}.gif"), "--format", "gif", "--resolution", "quarter", "--fps", "12")
    cli("render", proj, "--comp", "Main", "--out", os.path.join(out, f"{sid}.mp4"), "--format", "h264", "--resolution", "half")


def duration(sid):
    proj = os.path.join(KIT, "catalog", f"{sid}.ecproj")
    if not os.path.exists(proj):
        return None
    with open(proj) as f:
        p = json.load(f)
    for item in p.get("items", {}).values():
        kind = item.get("kind", {})
        if item.get("name") == "Main" and kind.get("type") == "Comp":
            d = kind.get("duration")
            return d / TICKS if isinstance(d, (int, float)) else None  # stored in ticks
    return None


def cell(text):
    """Table-safe: a "|" inside a cell would end it, even in a code span."""
    return str(text or "").replace("|", "\\|").replace("\n", " ")


def sources(value):
    """A proposal's "from": a list, or one string with comma-separated paths."""
    items = value if isinstance(value, list) else str(value or "").split(",")
    return [i.strip() for i in items if i and i.strip()]


def links(value):
    return ", ".join(f"[{os.path.basename(i).replace('.recipe.json', '')}]({i})" for i in sources(value))


def gif(path, width=320):
    return f'<img src="{path}" width="{width}">' if os.path.exists(os.path.join(KIT, path)) else "(no preview yet)"


def all_proposals():
    """Per-comp files (references/<slug>.proposals.json, inbox/*.proposals.json) plus proposals.json.
    The same id in several files is one proposal with its sources merged; proposals.json wins on
    status and note, so decisions are recorded there."""
    merged = {}
    for folder in ("references", "inbox"):
        d = os.path.join(KIT, folder)
        for f in sorted(os.listdir(d)) if os.path.isdir(d) else []:
            if f.endswith(".proposals.json"):
                for p in load(os.path.join(folder, f), {}).get("proposals", []):
                    if p.get("id") in merged:
                        m = merged[p["id"]]
                        m["from"] = sources(m.get("from")) + [x for x in sources(p.get("from")) if x not in sources(m.get("from"))]
                    else:
                        merged[p["id"]] = dict(p)
    for p in load("proposals.json", {"proposals": []}).get("proposals", []):
        if p.get("id") in merged:
            merged[p["id"]].update({k: v for k, v in p.items() if k in ("status", "note")})
        else:
            merged[p["id"]] = dict(p)
    return list(merged.values())


def main():
    cat = load("catalog.json", {"primitives": [], "scenes": []})
    props = all_proposals()
    os.makedirs(os.path.join(KIT, "catalog"), exist_ok=True)

    if "--no-render" not in sys.argv:
        for s in cat["scenes"]:
            print(f"rendering {s['id']}…", flush=True)
            render_scene(s["id"])

    md = [
        "# Motion kit catalog",
        "",
        "Generated by `python3 catalog.py` — don't edit by hand. Everything in the kit, with a preview;",
        "what agents propose; what's waiting in the inbox. Answer proposals with one word each:",
        "**yes**, **no**, or **merge with `<primitive>`**.",
        "",
        "## Primitives",
        "",
        "| Preview | Primitive | What it does | Call |",
        "|---|---|---|---|",
    ]
    for p in cat["primitives"]:
        md.append(f"| {gif('catalog/' + p['demo'] + '.gif')} | **`{p['id']}`**<br>[{p['file']}]({p['file']}) | {cell(p['what'])} | `{cell(p['call'])}` |")
    md += ["", "## Scenes", "", "| Preview | Scene | What it is | Build |", "|---|---|---|---|"]
    for s in cat["scenes"]:
        md.append(f"| {gif('catalog/' + s['id'] + '.gif')} | **{s['id']}**<br>[{s['id']}.jsx]({s['id']}.jsx) | {cell(s['what'])} | `./build.sh {s['id']}` |")

    open_props = [p for p in props if p.get("status", "proposed") == "proposed"]
    md += ["", f"## Proposed ({len(open_props)} waiting for you)", ""]
    groups = [
        ("template", "Templates: a whole comp, reusable with knobs", "Each keeps the comp exactly as made; the call lists what you'd change per video."),
        ("part", "Parts: distinctive pieces, reusable on their own", "Moves and elements taken out of one comp, even if they appear only there."),
        (None, "Patterns across comps (earlier pass)", "Found by looking for what repeats; many overlap the parts above."),
    ]
    for kind, title, note in groups:
        rows = [p for p in open_props if p.get("kind") == kind or (kind is None and p.get("kind") not in ("template", "part"))]
        if not rows:
            continue
        md += [f"### {title} ({len(rows)})", "", note, "",
               "| Preview | Proposal | What it would capture | Call it would enable | Overlaps | From |", "|---|---|---|---|---|---|"]
        for p in rows:
            prev = gif(p["gif"]) if p.get("gif") else "(no preview)"
            if p.get("previewNote"):
                prev += f"<br><sub>{cell(p['previewNote'])}</sub>"
            md.append(f"| {prev} | **{p['id']}**<br>{cell(p.get('title'))} | {cell(p.get('why'))} | `{cell(p.get('call'))}` | {cell(p.get('overlaps', '—'))} | {links(p.get('from'))} |")
        md.append("")
    if not open_props:
        md.append("Nothing proposed right now.")
    decided = [p for p in props if p.get("status", "proposed") != "proposed"]
    if decided:
        md += ["", "<details><summary>Decided</summary>", ""]
        md += [f"- **{p['id']}**: {p['status']}" + (f" ({p['note']})" if p.get("note") else "") for p in decided]
        md += ["", "</details>"]

    inbox = sorted(f for f in os.listdir(os.path.join(KIT, "inbox")) if f.endswith(".recipe.json")) if os.path.isdir(os.path.join(KIT, "inbox")) else []
    proposed_from = {src for p in props for src in sources(p.get("from"))}
    raw = [f for f in inbox if f"inbox/{f}" not in proposed_from]
    md += ["", f"## Inbox ({len(raw)} not yet looked at)", ""]
    md += [f"- [inbox/{f}](inbox/{f})" for f in raw] or ["Empty. During an edit, say “inbox this”."]
    md += ["", "Notes from the edits: [inbox/NOTES.md](inbox/NOTES.md)."]

    refs = sorted(f[: -len(".recipe.json")] for f in os.listdir(os.path.join(KIT, "references")) if f.endswith(".recipe.json")) if os.path.isdir(os.path.join(KIT, "references")) else []
    md += ["", f"## References ({len(refs)} converted comps)", ""]
    if refs:
        md += ["| Preview | Comp | Breakdown |", "|---|---|---|"]
        for r in refs:
            bd = f"[how it's made](references/{r}.breakdown.md)" if os.path.exists(os.path.join(KIT, "references", f"{r}.breakdown.md")) else "(not decomposed yet)"
            md.append(f"| {gif('references/' + r + '.gif')} | [{r}](references/{r}.recipe.json) | {bd} |")
        md += ["", "Details and rebuild checks: [references/README.md](references/README.md)."]
    else:
        md.append("None yet. Converted comps land here with their recipe and a GIF.")
    md.append("")
    with open(os.path.join(KIT, "CATALOG.md"), "w") as f:
        f.write("\n".join(md))

    entries = []
    for s in cat["scenes"]:
        if not os.path.exists(os.path.join(KIT, "catalog", f"{s['id']}.ecproj")):
            continue
        uses = [p["id"] for p in cat["primitives"] if p["demo"] == s["id"]]
        e = {"id": f"kit-{s['id']}", "name": f"Kit · {s['id']}", "kind": "comp", "file": f"catalog/{s['id']}.ecproj",
             "comp": "Main", "category": "Motion kit", "tags": ["motion-kit", *uses], "description": s["what"],
             "thumbnail": f"catalog/{s['id']}.png", "preview": f"catalog/{s['id']}.mp4"}
        d = duration(s["id"])
        if d:
            e["duration"] = round(d, 3)
        entries.append(e)
    for r in refs:
        e = {"id": f"ref-{r}", "name": f"Reference · {r}", "kind": "comp", "file": f"references/{r}.ecproj",
             "category": "Motion kit references", "tags": ["motion-kit", "reference"], "description": f"Rebuilt from references/{r}.recipe.json"}
        if os.path.exists(os.path.join(KIT, "references", f"{r}.ecproj")):
            entries.append(e)
    with open(os.path.join(KIT, "library.json"), "w") as f:
        json.dump({"format": "effectcraft-library", "version": 1, "name": "Motion kit", "entries": entries}, f, indent=2)
        f.write("\n")
    print(f"CATALOG.md: {len(cat['primitives'])} primitives, {len(cat['scenes'])} scenes, {len(open_props)} proposed, {len(raw)} in inbox, {len(refs)} references")
    print(f"library.json: {len(entries)} entries")


if __name__ == "__main__":
    main()
